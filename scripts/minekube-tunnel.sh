#!/usr/bin/env bash
# Expose the local Minecraft server through Minekube Connect.
#
# Minekube's fast-start Connect plugin is a Paper/Spigot/Velocity/BungeeCord
# plugin and cannot be loaded by a Fabric server. Gate is Minekube's own
# Minecraft proxy and the supported platform-independent Connect connector,
# so it provides the same public <endpoint>.play.minekube.net address for this
# Fabric server without any Paper plugin.
#
# Gate runs next to the Fabric server, accepts players from the Connect edge
# network over an outbound tunnel and forwards them to 127.0.0.1:25565. No
# router port forwarding or public IP address is required.
#
# The Gate binary is downloaded into .agent-work/tools and is never committed.
# The script writes the public address to SERVER_ADDRESS.txt and leaves Gate
# running in the background. The PID is stored in:
#   ${TUNNEL_PID_FILE:-${RUNNER_TEMP:-<repo>/.agent-work/tmp}/ultron-tunnel.pid}
#
# Optional environment variables:
#   MINECRAFT_PORT                Local Fabric server port (default: 25565)
#   MINEKUBE_ENDPOINT             Stable endpoint name (1-16 lowercase
#                                 letters, digits or hyphens)
#   MINEKUBE_CONNECT_TOKEN        Connector token for a stable endpoint.
#                                 Never commit or log this value.
#   MINEKUBE_GATE_VERSION         Gate release to download (default: 0.81.1)
#   MINEKUBE_GATE_DOWNLOAD_URL    Override the Gate download URL
#   GATE_BIN                      Use an existing Gate binary (used by tests)
#   MINEKUBE_BIND_ADDR            Local Gate listener address (default:
#                                 127.0.0.1)
#   MINEKUBE_BIND_PORT            Local Gate listener port (default: 25566)
#   MINEKUBE_DOMAIN               Connect endpoint domain (default:
#                                 play.minekube.net)
#   MINEKUBE_ALLOW_OFFLINE_PLAYERS
#                                 Allow offline/cracked players through
#                                 Connect (default: true)
#   MINEKUBE_READY_TIMEOUT        Seconds to wait for registration
#                                 (default: 90)
#   MINEKUBE_ENDPOINT_FALLBACK    Fall back to a temporary endpoint when an
#                                 explicitly configured name cannot be used
#                                 without a token (default: true)
#   MINEKUBE_DATA_DIR             State/config directory
#                                 (default: .agent-work/tmp/minekube)
#   MINEKUBE_CONFIG_FILE          Generated Gate config file
#   MINEKUBE_TOKEN_FILE           Gate connect.json token file
#   MINEKUBE_STATE_FILE           File remembering the temporary endpoint
#                                 name across tunnel restarts
#   MINEKUBE_WATCH_SERVICE_ADDR   Connect watch service address
set -euo pipefail

ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
TOOLS_DIR="$ROOT_DIR/.agent-work/tools"
LOGS_DIR="$ROOT_DIR/.agent-work/logs"
ADDRESS_FILE="$ROOT_DIR/SERVER_ADDRESS.txt"
DEFAULT_PID_DIR="${RUNNER_TEMP:-$ROOT_DIR/.agent-work/tmp}"
PID_FILE="${TUNNEL_PID_FILE:-$DEFAULT_PID_DIR/ultron-tunnel.pid}"

LOCAL_PORT="${MINECRAFT_PORT:-25565}"
GATE_VERSION="${MINEKUBE_GATE_VERSION:-0.81.1}"
BIND_ADDR="${MINEKUBE_BIND_ADDR:-127.0.0.1}"
BIND_PORT="${MINEKUBE_BIND_PORT:-25566}"
DOMAIN="${MINEKUBE_DOMAIN:-play.minekube.net}"
READY_TIMEOUT="${MINEKUBE_READY_TIMEOUT:-90}"
ALLOW_OFFLINE="${MINEKUBE_ALLOW_OFFLINE_PLAYERS:-true}"
WATCH_ADDR="${MINEKUBE_WATCH_SERVICE_ADDR:-wss://watch-connect.minekube.net}"
ENDPOINT_FALLBACK="${MINEKUBE_ENDPOINT_FALLBACK:-true}"

DATA_DIR="${MINEKUBE_DATA_DIR:-$ROOT_DIR/.agent-work/tmp/minekube}"
CONFIG_FILE="${MINEKUBE_CONFIG_FILE:-$DATA_DIR/config.yml}"
TOKEN_FILE="${MINEKUBE_TOKEN_FILE:-$DATA_DIR/connect.json}"
STATE_FILE="${MINEKUBE_STATE_FILE:-$DATA_DIR/endpoint}"
TUNNEL_LOG="$LOGS_DIR/minekube-tunnel.log"

REQUESTED_ENDPOINT="$(printf '%s' "${MINEKUBE_ENDPOINT:-}" | tr '[:upper:]' '[:lower:]')"
CONNECT_TOKEN="${MINEKUBE_CONNECT_TOKEN:-}"
GATE_BIN="${GATE_BIN:-}"
GATE_STARTED=0

mkdir -p "$TOOLS_DIR" "$LOGS_DIR" "$DATA_DIR" "$(dirname -- "$PID_FILE")"

detect_os() {
    case "$(uname -s)" in
        Linux) echo "linux" ;;
        Darwin) echo "darwin" ;;
        *)
            echo "ERROR: unsupported operating system: $(uname -s)" >&2
            return 1
            ;;
    esac
}

detect_arch() {
    case "$(uname -m)" in
        x86_64 | amd64) echo "amd64" ;;
        aarch64 | arm64) echo "arm64" ;;
        *)
            echo "ERROR: unsupported CPU architecture: $(uname -m)" >&2
            return 1
            ;;
    esac
}

strip_ansi() {
    sed -E $'s/\x1B\\[[0-9;]*[mK]//g'
}

valid_endpoint() {
    local name="$1"

    # Minekube currently accepts 1-16 lowercase alphanumeric/hyphen
    # characters and rejects longer random names generated by some Gate
    # versions, so validate the name ourselves before starting Gate.
    [ "${#name}" -ge 1 ] && [ "${#name}" -le 16 ] \
        && printf '%s' "$name" | grep -qE '^[a-z0-9]([a-z0-9-]*[a-z0-9])?$'
}

generate_endpoint() {
    local suffix

    suffix="$(od -An -N4 -tx1 /dev/urandom 2>/dev/null | tr -d ' \n' || true)"
    if [ -z "$suffix" ]; then
        suffix="$(printf '%04x%04x' "$RANDOM" "$RANDOM")"
    fi
    printf 'ultron-%s' "$suffix"
}

ensure_gate() {
    if [ -n "$GATE_BIN" ]; then
        if [ ! -x "$GATE_BIN" ]; then
            echo "ERROR: GATE_BIN is not executable: $GATE_BIN" >&2
            return 1
        fi
        return 0
    fi

    local os arch asset download_url download_dir
    os="$(detect_os)"
    arch="$(detect_arch)"
    GATE_BIN="$TOOLS_DIR/gate-${GATE_VERSION}-${os}-${arch}"

    if [ -x "$GATE_BIN" ]; then
        return 0
    fi

    asset="gate_${GATE_VERSION}_${os}_${arch}"
    download_url="${MINEKUBE_GATE_DOWNLOAD_URL:-https://github.com/minekube/gate/releases/download/v${GATE_VERSION}/${asset}}"
    download_dir="$TOOLS_DIR/.gate-download-$$"
    mkdir -p "$download_dir"
    trap 'rm -rf "$download_dir"' EXIT

    echo "Downloading Minekube Gate ${GATE_VERSION} for ${os}/${arch}..." >&2
    curl -fsSL --retry 3 --connect-timeout 15 "$download_url" \
        -o "$download_dir/gate"
    install -m 0755 "$download_dir/gate" "$GATE_BIN"
    rm -rf "$download_dir"
    trap - EXIT

    return 0
}

stop_existing_tunnel() {
    if [ ! -f "$PID_FILE" ]; then
        return 0
    fi

    local old_pid
    old_pid="$(cat "$PID_FILE" 2>/dev/null || true)"
    if [ -n "$old_pid" ] && kill -0 "$old_pid" 2>/dev/null; then
        kill "$old_pid" 2>/dev/null || true
        for _ in $(seq 1 20); do
            kill -0 "$old_pid" 2>/dev/null || break
            sleep 0.2
        done
        kill -9 "$old_pid" 2>/dev/null || true
    fi
    rm -f "$PID_FILE"
}

write_token_file() {
    if [ -z "$CONNECT_TOKEN" ]; then
        return 0
    fi

    python3 - "$CONNECT_TOKEN" "$TOKEN_FILE" <<'PY'
import json
import os
import sys
import tempfile

token, path = sys.argv[1], sys.argv[2]
directory = os.path.dirname(path) or "."
os.makedirs(directory, exist_ok=True)
fd, tmp = tempfile.mkstemp(dir=directory, prefix=".connect-", suffix=".json")
try:
    with os.fdopen(fd, "w", encoding="utf-8") as stream:
        json.dump({"token": token}, stream)
    os.chmod(tmp, 0o600)
    os.replace(tmp, path)
finally:
    if os.path.exists(tmp):
        os.unlink(tmp)
PY
}

write_config() {
    local endpoint="$1"
    local offline="false"

    if [ "$ALLOW_OFFLINE" = "true" ]; then
        offline="true"
    fi

    {
        echo "# Generated by scripts/minekube-tunnel.sh - do not commit."
        echo "config:"
        echo "  bind: \"${BIND_ADDR}:${BIND_PORT}\""
        echo "  onlineMode: false"
        echo "  forceKeyAuthentication: false"
        echo "  forwarding:"
        echo "    mode: none"
        echo "  connectionTimeout: 10s"
        echo "  readTimeout: 60s"
        echo "  compression:"
        echo "    threshold: 128"
        echo "  servers:"
        echo "    ultron: \"127.0.0.1:${LOCAL_PORT}\""
        echo "  try:"
        echo "    - ultron"
        echo "  status:"
        echo "    motd: |"
        echo "      §bUltron SMP"
        echo "      §7via Minekube Connect"
        echo "    showMaxPlayers: 100"
        echo "connect:"
        echo "  enabled: true"
        echo "  name: \"${endpoint}\""
        echo "  allowOfflineModePlayers: ${offline}"
        echo "  tokenFilePath: \"${TOKEN_FILE}\""
        echo "  watchServiceAddr: \"${WATCH_ADDR}\""
    } >"$CONFIG_FILE"
}

write_address() {
    local endpoint="$1"
    local address="${endpoint}.${DOMAIN}:25565"
    local tmp="$ADDRESS_FILE.tmp"

    {
        echo "# Ultron SMP public server address"
        echo "# Updated: $(date -u '+%Y-%m-%d %H:%M:%S UTC')"
        echo "# Provider: Minekube Connect (Gate ${GATE_VERSION}, endpoint ${endpoint})"
        echo "# Add this server in Minecraft (host and port):"
        echo "$address"
        echo "#"
        echo "# Host: ${endpoint}.${DOMAIN}"
        echo "# Port: 25565"
    } >"$tmp"
    mv "$tmp" "$ADDRESS_FILE"

    echo "$address"
}

start_gate() {
    local endpoint="$1"
    local gate_pid=""
    local log_start=0

    write_config "$endpoint"

    {
        echo "=== $(date -u '+%Y-%m-%d %H:%M:%S UTC') starting Gate ${GATE_VERSION} endpoint=${endpoint} ==="
    } >>"$TUNNEL_LOG"

    if [ -f "$TUNNEL_LOG" ]; then
        log_start="$(wc -l <"$TUNNEL_LOG" 2>/dev/null || echo 0)"
    fi

    nohup "$GATE_BIN" -c "$CONFIG_FILE" \
        >>"$TUNNEL_LOG" 2>&1 </dev/null &
    gate_pid=$!
    GATE_STARTED=1

    local attempts=$((READY_TIMEOUT * 4))
    local new_log
    for _ in $(seq 1 "$attempts"); do
        if ! kill -0 "$gate_pid" 2>/dev/null; then
            break
        fi

        new_log="$(tail -n "+$((log_start + 1))" "$TUNNEL_LOG" 2>/dev/null || true)"
        if printf '%s' "$new_log" \
            | grep -qE 'connect[^ ]*[[:space:]].*connected|connected[[:space:]]+\{"took"'; then
            echo "$gate_pid" >"$PID_FILE"
            return 0
        fi

        # These errors cannot be fixed by waiting for another retry.
        if printf '%s' "$new_log" \
            | grep -qiE 'invalid endpoint name format|missing required header|status[^ ]*401|unauthorized'; then
            break
        fi

        sleep 0.25
    done

    kill "$gate_pid" 2>/dev/null || true
    wait "$gate_pid" 2>/dev/null || true
    GATE_STARTED=0
    return 1
}

on_exit() {
    if [ "$GATE_STARTED" -eq 1 ]; then
        local pid
        pid="$(cat "$PID_FILE" 2>/dev/null || true)"
        if [ -n "$pid" ]; then
            kill "$pid" 2>/dev/null || true
        fi
    fi
}
trap on_exit EXIT

if ! ensure_gate; then
    echo "ERROR: the Minekube Gate connector could not be installed." >&2
    exit 1
fi

stop_existing_tunnel
write_token_file

endpoint="$REQUESTED_ENDPOINT"
if [ -z "$endpoint" ]; then
    if [ -n "$CONNECT_TOKEN" ]; then
        endpoint="ultron-smp"
    elif [ -f "$STATE_FILE" ]; then
        endpoint="$(head -n 1 "$STATE_FILE" 2>/dev/null | tr '[:upper:]' '[:lower:]')"
    fi
fi
if [ -z "$endpoint" ]; then
    endpoint="$(generate_endpoint)"
fi

if ! valid_endpoint "$endpoint"; then
    if [ -n "$REQUESTED_ENDPOINT" ]; then
        echo "ERROR: MINEKUBE_ENDPOINT '${endpoint}' is invalid (use 1-16 lowercase letters, digits or hyphens)." >&2
        exit 1
    fi
    endpoint="$(generate_endpoint)"
fi

if start_gate "$endpoint"; then
    printf '%s\n' "$endpoint" >"$STATE_FILE"
else
    # An explicitly configured endpoint without a token may already belong to
    # another connector. Use a temporary endpoint instead so the server stays
    # reachable instead of failing the whole run.
    if [ -z "$CONNECT_TOKEN" ] && [ -n "$REQUESTED_ENDPOINT" ] \
        && [ "$ENDPOINT_FALLBACK" = "true" ]; then
        echo "WARNING: Minekube endpoint '${endpoint}' is unavailable (it may be owned by another connector or require a token)." >&2
        echo "Falling back to a temporary Minekube endpoint for this run..." >&2
        rm -f "$TOKEN_FILE"
        endpoint="$(generate_endpoint)"
        if start_gate "$endpoint"; then
            printf '%s\n' "$endpoint" >"$STATE_FILE"
        else
            strip_ansi <"$TUNNEL_LOG" | tail -n 30 >&2 || true
            echo "ERROR: could not establish a Minekube Connect tunnel." >&2
            exit 1
        fi
    else
        strip_ansi <"$TUNNEL_LOG" | tail -n 30 >&2 || true
        echo "ERROR: could not establish a Minekube Connect tunnel for endpoint '${endpoint}'." >&2
        exit 1
    fi
fi

GATE_STARTED=0
trap - EXIT
echo "Tunnel is live at $(write_address "$endpoint")"

if [ -z "$CONNECT_TOKEN" ] && [ -f "$TOKEN_FILE" ]; then
    echo "NOTE: Gate stored a connector token in ${TOKEN_FILE}. To keep the endpoint '${endpoint}' between runs, set the repository variable MINEKUBE_ENDPOINT to '${endpoint}' and the secret MINEKUBE_CONNECT_TOKEN to the token from that file (or from app.minekube.com)." >&2
fi
