#!/usr/bin/env python3
"""Regenerate src/main/resources/heads-textures.tsv from DropHeads data.

The DropHeads project publishes base64-encoded textures for every mob variant.
This script keeps only the base entity entries and resolves the handful of
aliases that point at another entry (for example AXOLOTL -> AXOLOTL|LUCY).
"""
import collections
import os
import re
import sys
import urllib.request

SOURCE = "https://raw.githubusercontent.com/EvModder/DropHeads/master/extra-textures/head-textures-base64s.txt"
HERE = os.path.dirname(os.path.abspath(__file__))
OUTPUT = os.path.join(HERE, "src", "main", "resources", "heads-textures.tsv")


def read_source(path):
    if path:
        with open(path, encoding="utf-8") as stream:
            return stream.read()
    request = urllib.request.Request(SOURCE, headers={"User-Agent": "ultron-smp/1.0"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read().decode("utf-8")


def main():
    source = sys.argv[1] if len(sys.argv) > 1 else None
    entries = {}
    order = []
    for line in read_source(source).splitlines():
        line = line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, value = line.split(":", 1)
        key, value = key.strip(), value.strip()
        if not re.fullmatch(r"[A-Z0-9_|]+", key) or not value:
            continue
        entries[key] = value
        if key not in order:
            order.append(key)

    def resolve(key, seen=()):
        if key in seen:
            return None
        value = entries.get(key)
        if not value or value == "xxx":
            return None
        if value in entries:
            return resolve(value, seen + (key,))
        if re.fullmatch(r"[A-Za-z0-9+/]+={0,2}", value) and len(value) > 40:
            return value
        return None

    bases = collections.OrderedDict()
    for key in order:
        if "|" in key:
            continue
        value = resolve(key)
        if value:
            bases[key] = value

    with open(OUTPUT, "w", encoding="utf-8") as stream:
        stream.write("# Minecraft mob head textures. Format: ENTITY_TYPE<TAB>base64 textures property\n")
        stream.write("# Generated by paper-plugin/generate-textures.py from EvModder/DropHeads data.\n")
        for key, value in bases.items():
            stream.write(f"{key}\t{value}\n")
    print(f"Wrote {len(bases)} textures to {OUTPUT}")


if __name__ == "__main__":
    main()
